#!/usr/bin/env python3
"""Apply the iOS 27 scene lifecycle patch to the benchmark apps.

iOS 27 requires UIScene: React Native is started from a SceneDelegate and Info.plist gets a
UIApplicationSceneManifest. The bare apps have it committed; apps/nativewind5 is generated by
`expo prebuild --clean`, which drops it, so run this again after every prebuild.

Usage: scripts/bench/scene-patch.py [app-dir-name ...]   (default: every app in configs.json)
Idempotent: already patched apps are skipped.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SCENE = '''
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    appDelegate.reactNativeFactory?.startReactNative(withModuleName: "%s", in: window, launchOptions: nil)
  }
}
'''

MANIFEST = json.dumps({
    "UIApplicationSupportsMultipleScenes": False,
    "UISceneConfigurations": {
        "UIWindowSceneSessionRoleApplication": [{
            "UISceneConfigurationName": "Default",
            "UISceneDelegateClassName": "$(PRODUCT_MODULE_NAME).SceneDelegate",
        }],
    },
}, separators=(",", ":"))

EXPO_START = re.compile(
    r'\n#if os\(iOS\) \|\| os\(tvOS\)\n    window = UIWindow\(frame: UIScreen.main.bounds\)\n'
    r'    factory.startReactNative\(\n      withModuleName: "(\w+)",\n      in: window,\n'
    r'      launchOptions: launchOptions\)\n#endif\n')
BARE_START = re.compile(
    r'\n    window = UIWindow\(frame: UIScreen.main.bounds\)\n\n    factory.startReactNative\(\n'
    r'      withModuleName: "(\w+)",\n      in: window,\n      launchOptions: launchOptions\n    \)\n')


def has_manifest(plist: Path) -> bool:
    r = subprocess.run(["plutil", "-extract", "UIApplicationSceneManifest", "raw", str(plist)],
                       capture_output=True, text=True)
    return r.returncode == 0


def patch(delegate: Path, plist: Path, expo: bool) -> None:
    src = delegate.read_text()
    name = delegate.relative_to(ROOT)
    if "UIWindowSceneDelegate" in src:
        print(f"already patched {name}")
    else:
        m = (EXPO_START if expo else BARE_START).search(src)
        if not m:
            sys.exit(f"window setup not found in {delegate} (template changed?)")
        src = src[:m.start()] + src[m.end():]
        delegate.write_text(src.rstrip("\n") + "\n" + SCENE % m.group(1))
        print(f"patched {name} (module {m.group(1)})")
    if not has_manifest(plist):
        subprocess.run(["plutil", "-insert", "UIApplicationSceneManifest", "-json", MANIFEST, str(plist)],
                       check=True)
        print(f"added UIApplicationSceneManifest to {plist.relative_to(ROOT)}")


def main() -> None:
    configs = json.loads((ROOT / "scripts/bench/configs.json").read_text())["configs"]
    apps = {}
    for c in configs:
        apps.setdefault(Path(c["app"]).name, (c["app"], c["ios"]["scheme"], c["expo"]))
    wanted = sys.argv[1:] or list(apps)
    for name in wanted:
        if name not in apps:
            sys.exit(f"unknown app '{name}', expected one of: {', '.join(apps)}")
        app, target, expo = apps[name]
        d = ROOT / app / "ios" / target
        if not d.is_dir():
            sys.exit(f"{d} does not exist (run `bunx expo prebuild --clean` first for Expo apps)")
        patch(d / "AppDelegate.swift", d / "Info.plist", expo)


if __name__ == "__main__":
    main()
